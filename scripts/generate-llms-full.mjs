import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repository = 'winterdrive/vscode-virtual-tabs';
const branch = 'main';
const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(scriptDirectory, '..');
const outputPath = path.join(projectRoot, 'docs', 'llms-full.txt');

const sources = [
  ['Product overview and usage', 'README.md'],
  ['Product philosophy', 'docs/PHILOSOPHY.md'],
  ['MCP client setup', 'docs/mcp-setup.md'],
  ['MCP server reference', 'mcp-server/README.md'],
  ['Agent Skill behavior and safety', 'skills/virtualtabs/SKILL.md'],
  ['Development and extension architecture', 'DEVELOPMENT.md'],
  ['Testing', 'docs/TESTING.md'],
  ['Contributing', 'CONTRIBUTING.md'],
  ['Localization and translation policy', 'I18N.md'],
  ['Release policy', 'docs/RELEASE_POLICY.md'],
  ['Release history', 'CHANGELOG.md'],
];

function rawUrl(repositoryPath) {
  return `https://raw.githubusercontent.com/${repository}/${branch}/${encodeURI(repositoryPath)}`;
}

function rewriteRelativeLinks(markdown, sourcePath) {
  const sourceDirectory = path.posix.dirname(sourcePath);

  return markdown.replace(/(!?\[[^\]]*\]\()([^)]+)(\))/g, (match, prefix, rawTarget, suffix) => {
    const target = rawTarget.trim().replace(/^<|>$/g, '');

    if (/^(?:[a-z][a-z0-9+.-]*:|#)/i.test(target)) {
      return match;
    }

    const targetMatch = target.match(/^([^?#]*)(\?[^#]*)?(#.*)?$/);
    if (!targetMatch || !targetMatch[1]) {
      return match;
    }

    const [, targetPath, query = '', fragment = ''] = targetMatch;
    const repositoryPath = targetPath.startsWith('/')
      ? path.posix.normalize(targetPath.slice(1))
      : path.posix.normalize(path.posix.join(sourceDirectory, targetPath));

    return `${prefix}${rawUrl(repositoryPath)}${query}${fragment}${suffix}`;
  });
}

function buildOutput() {
  const sourceIndex = sources
    .map(([title, sourcePath]) => `- [${title}](${rawUrl(sourcePath)}): \`${sourcePath}\``)
    .join('\n');

  const documents = sources
    .map(([title, sourcePath]) => {
      const absolutePath = path.join(projectRoot, ...sourcePath.split('/'));
      const markdown = fs.readFileSync(absolutePath, 'utf8')
        .replace(/\r\n/g, '\n')
        .replace(/[ \t]+$/gm, '')
        .trim();
      const rewritten = rewriteRelativeLinks(markdown, sourcePath);

      return [
        `<!-- BEGIN CANONICAL SOURCE: ${sourcePath} -->`,
        `Source: [${title}](${rawUrl(sourcePath)})`,
        '',
        rewritten,
        '',
        `<!-- END CANONICAL SOURCE: ${sourcePath} -->`,
      ].join('\n');
    })
    .join('\n\n---\n\n');

  return [
    '<!-- GENERATED FILE — DO NOT EDIT DIRECTLY. -->',
    '<!-- Run `npm run docs:llms` after changing a canonical source. -->',
    '',
    '# VirtualTabs Full Context Documentation',
    '',
    '> Generated aggregate of the canonical VirtualTabs documentation for LLM consumers.',
    '',
    'The linked source documents remain authoritative. This file is a deterministic',
    'consumer artifact generated by `scripts/generate-llms-full.mjs`.',
    '',
    '## Included canonical sources',
    '',
    sourceIndex,
    '',
    '---',
    '',
    documents,
    '',
  ].join('\n');
}

const generated = buildOutput();

if (process.argv.includes('--check')) {
  const current = fs.existsSync(outputPath)
    ? fs.readFileSync(outputPath, 'utf8').replace(/\r\n/g, '\n')
    : '';

  if (current !== generated) {
    console.error('docs/llms-full.txt is stale. Run `npm run docs:llms` and commit the result.');
    process.exit(1);
  }

  console.log('docs/llms-full.txt is up to date.');
} else {
  fs.writeFileSync(outputPath, generated, 'utf8');
  console.log('Generated docs/llms-full.txt.');
}
